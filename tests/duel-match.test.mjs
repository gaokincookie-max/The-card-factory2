import assert from 'node:assert/strict';
import {createDuel,advanceDuel,applyDuelCommand,exportDuelSnapshot,importDuelSnapshot,getDuelView} from '../src/duel-match.js';
import fs from 'node:fs';
const stats=JSON.parse(fs.readFileSync(new URL('../data/unit-stats.json',import.meta.url)));
const g=createDuel({stats});
assert.ok(g.battle.multiplayer);assert.notEqual(g.factories[0],g.factories[1]);
assert.equal(applyDuelCommand(g,0,{type:'BUILD_FACILITY',payload:{kind:'smelter',x:8,y:8}}).ok,true);
assert.equal(g.factories[1].buildings.length,0);
assert.equal(applyDuelCommand(g,1,{type:'BUILD_FACILITY',payload:{kind:'smelter',x:8,y:8}}).ok,true);
assert.equal(g.factories[0].buildings.length,1);
g.factories[0].hand[0]={name:'歩兵分隊',mods:[]};g.factories[1].hand[2]={name:'歩兵分隊',mods:[]};
assert.equal(applyDuelCommand(g,0,{type:'DEPLOY_UNIT',payload:{slot:0,column:0,row:0}}).ok,true);
assert.equal(applyDuelCommand(g,1,{type:'DEPLOY_UNIT',payload:{slot:2,column:0,row:0}}).ok,true);
assert.equal(g.battle.units[0][0][0].team,0);assert.equal(g.battle.units[1][0][0].team,1);
assert.equal(g.factories[0].hand[0],null);assert.equal(g.factories[1].hand[2],null);
g.factories[1].hand[0]={name:'緊急資材調達',mods:[]};const m=g.factories.map(f=>f.money);
assert.equal(applyDuelCommand(g,1,{type:'PLAY_CARD',payload:{slot:0}}).ok,true);
assert.ok(g.factories[1].money>m[1]);assert.equal(g.factories[0].money,m[0]);
const view=getDuelView(g,0);assert.equal(view.factories,undefined);assert.equal(view.opponent.factory,undefined);
assert.equal(view.factory.hand[2],null);view.factory.money=9999;assert.notEqual(g.factories[0].money,9999);
let before=g.factories.map(f=>f.tick);advanceDuel(g,0.1);assert.ok(g.factories.every((f,i)=>f.tick>before[i]));
const snap=exportDuelSnapshot(g),restored=importDuelSnapshot(snap);
assert.deepEqual(exportDuelSnapshot(restored),snap);
for(let i=0;i<50;i++){advanceDuel(g,0.1);advanceDuel(restored,0.1)}
assert.deepEqual(exportDuelSnapshot(restored),exportDuelSnapshot(g));
assert.equal(g.battle.units[1][1][0],null,'CPU must not spawn in multiplayer');
assert.equal(applyDuelCommand(g,2,{type:'DEPLOY_UNIT',payload:{slot:0,column:0,row:0}}).ok,false);
console.log('PASS 2 independent factories, shared battle, both team commands, privacy, snapshot');
const h=createDuel({stats});
h.factories[1].hand[0]={name:'歩兵分隊',mods:[]};
assert.equal(applyDuelCommand(h,1,{type:'DEPLOY_UNIT',payload:{slot:0,column:2,row:0}}).ok,true);
h.factories[1].hand[1]={name:'応急処置',mods:[]};
h.battle.units[1][2][0].hp=1;
assert.equal(applyDuelCommand(h,1,{type:'PLAY_CARD',payload:{slot:1,target:{team:1,column:2,row:0}}}).ok,true);
assert.ok(h.battle.units[1][2][0].hp>1);
h.factories[1].hand[2]={name:'集中砲撃',mods:[]};
assert.equal(applyDuelCommand(h,1,{type:'PLAY_CARD',payload:{slot:2,target:{team:1,column:2,row:0}}}).ok,false,'cannot fire on own team');
assert.ok(h.factories[1].hand[2]);
assert.equal(applyDuelCommand(h,0,{type:'SELF_DESTRUCT',payload:{column:2,row:0}}).ok,false,'cannot self destruct opponent units');
const hidden=getDuelView(h,0);
assert.equal(JSON.stringify(hidden).includes('factories'),false);
assert.equal(JSON.stringify(hidden).includes('warehouseFilter'),false);
console.log('PASS team1 support routing and rejected unauthorized targets');
