assert.equal(s.attach('bob'),1);
assert.equal(s.phase,'playing');
assert.throws(()=>s.attach('charlie'));
assert.equal(s.command('bob',{type:'BUILD_FACILITY',payload:{kind:'smelter',x:8,y:8}}).ok,true);
assert.equal(s.command('alice',{type:'BUILD_FACILITY',payload:{kind:'smelter',x:8,y:8}}).ok,true);
