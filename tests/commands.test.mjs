import assert from 'node:assert/strict';
import {initialState} from '../src/engine.js';
import {createBattle} from '../src/battle.js';
import {executeCommand} from '../src/commands.js';
import {FACTORY_RULES,BATTLE_RULES} from '../src/rules-config.js';
import {catalog,recipes} from '../src/engine.js';
const factory=initialState(),battle=createBattle(factory),game={factory,battle};
assert.equal(factory.money,FACTORY_RULES.startMaterials);
assert.equal(battle.ready,BATTLE_RULES.preparationSeconds);
assert.ok(Object.keys(catalog).length>10 && Object.keys(recipes).length>3);
assert.equal(executeCommand(game,{type:'MISSING'}).ok,false);
assert.equal(executeCommand(game,{type:'BUILD_FACILITY',payload:{kind:'smelter',x:8,y:8}}).ok,true);
assert.equal(factory.buildings.length,1);
assert.equal(executeCommand(game,{type:'BUILD_FACILITY',payload:{kind:'smelter',x:8,y:8}}).ok,false);
assert.equal(executeCommand(game,{type:'SELECT_RECIPE',payload:{buildingId:factory.buildings[0].id,recipeId:'iron_bar'}}).ok,true);
assert.equal(factory.buildings[0].recipe,'iron_bar');
assert.equal(executeCommand(game,{type:'SELF_DESTRUCT',payload:{column:0,row:0}}).ok,false);
assert.equal(executeCommand(game,{type:'PLACE_BELT',payload:{x1:4,y1:8,x2:7,y2:8}}).ok,true);
console.log('PASS shared command API and rule data');
