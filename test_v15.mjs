import assert from 'node:assert/strict';
import {createBattle,activateSupportFromHand,supportTargetType} from './src/battle.js';
import {initialState,place,warehouseStock,step} from './src/engine.js';
const s=initialState();
assert.equal(place(s,'warehouseSmall',7,7),null);
const wh=s.buildings[0];wh.inventory['{"name":"鉄材","mods":[]}']=2;
const b=createBattle(s);
s.hand[0]={name:'緊急搬送',mods:[]};
assert.equal(supportTargetType('緊急搬送'),'warehouse');
assert.equal(activateSupportFromHand(b,0).needsTarget,true);
const key=warehouseStock(wh)[0].key;
assert.equal(activateSupportFromHand(b,0,{buildingId:wh.id,itemKey:key}).ok,true);
assert.equal(warehouseStock(wh)[0].count,1);
assert.equal(s.hand[0].name,'鉄材');
s.hand[2]={name:'生産加速',mods:[]};
assert.equal(place(s,'smelter',9,9),null);
const sm=s.buildings.at(-1);
assert.equal(activateSupportFromHand(b,2,{buildingId:wh.id}).ok,false);
assert.equal(s.hand[2].name,'生産加速');
assert.equal(activateSupportFromHand(b,2,{buildingId:sm.id}).ok,true);
assert.equal(sm.fastUntil,s.tick+12);
console.log('PASS v1.5 emergency transport and production boost; invalid target preserves card');
// A full hand must keep the emergency transport card untouched.
const full=initialState();
assert.equal(place(full,'warehouseSmall',7,7),null);
const fullWh=full.buildings[0];fullWh.inventory['{"name":"鉄材","mods":[]}']=1;
full.hand=Array.from({length:8},(_,i)=>({name:i===0?'緊急搬送':'鉄材',mods:[]}));
const fullBattle=createBattle(full);
const result=activateSupportFromHand(fullBattle,0,{buildingId:fullWh.id,itemKey:warehouseStock(fullWh)[0].key});
assert.equal(result.ok,false);assert.equal(full.hand[0].name,'緊急搬送');
assert.equal(warehouseStock(fullWh)[0].count,1);
console.log('PASS full-hand emergency transport preserves support and warehouse inventory');
